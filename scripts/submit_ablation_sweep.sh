#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'USAGE'
Usage: scripts/submit_ablation_sweep.sh --cluster narval|fir|local [options]

Prints a proposal-focused, one-factor-at-a-time ablation sweep by default.
Pass --submit to enqueue the generated end-to-end pipelines. With --cluster
local, --submit runs the variants one after another on this machine's GPU.

Options:
  --config PATH          Standalone ablation YAML (default: configs/ablations.yaml)
  --prefix NAME          Unique run-name prefix (default: qwen3_0_6b_ablation)
  --account NAME         Slurm account (default: def-krallen; ignored locally)
  --set KEY=VALUE        Apply an override to every variant; repeatable
  --submit               Submit (or, locally, run) jobs (default is a dry run)
  -h, --help             Show this help

Variants:
  trained-mixed-p50      reference selector/probe setting
  trained-teacher-p50    teacher-only Stage 1 inputs
  trained-mixed-p300     longer probe optimization
  untrained-mixed-p0     initialization-only selector score
  stage2-teacher         teacher-only local reconstruction
  stage2-fixed05         fixed 0.5 teacher/student prefix mixture

Every pipeline evaluates its retained Stage 2 checkpoint and its Stage 3 checkpoint.
The reference variant provides scheduled 1.0->0.5 Stage 2. SWM-global selection is generated by
submit_baseline_pipeline.sh rather than duplicated here.
USAGE
}

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd -- "${script_dir}/.." && pwd)"
cluster=""
config_path="${repo_root}/configs/ablations.yaml"
prefix="qwen3_0_6b_ablation"
account="def-krallen"
submit=0
global_overrides=()
global_override_count=0

safe_name() {
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]]
}

while (($#)); do
  case "$1" in
    --cluster)
      [[ $# -ge 2 ]] || { echo "--cluster requires narval, fir, or local" >&2; exit 2; }
      cluster="$2"
      shift 2
      ;;
    --config)
      [[ $# -ge 2 ]] || { echo "--config requires a path" >&2; exit 2; }
      config_path="$2"
      shift 2
      ;;
    --prefix)
      [[ $# -ge 2 ]] || { echo "--prefix requires a name" >&2; exit 2; }
      prefix="$2"
      shift 2
      ;;
    --account)
      [[ $# -ge 2 ]] || { echo "--account requires a name" >&2; exit 2; }
      account="$2"
      shift 2
      ;;
    --set)
      [[ $# -ge 2 ]] || { echo "--set requires KEY=VALUE" >&2; exit 2; }
      global_overrides+=("$2")
      global_override_count=$((global_override_count + 1))
      shift 2
      ;;
    --set=*)
      global_overrides+=("${1#--set=}")
      global_override_count=$((global_override_count + 1))
      shift
      ;;
    --submit)
      submit=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

case "${cluster}" in
  narval|fir|local) ;;
  *) echo "--cluster must be narval, fir, or local" >&2; exit 2 ;;
esac
safe_name "${prefix}" || { echo "--prefix contains unsafe path characters" >&2; exit 2; }
[[ -n "${account}" ]] || { echo "--account cannot be empty" >&2; exit 2; }
if [[ "${config_path}" != /* ]]; then
  config_path="${repo_root}/${config_path}"
fi
[[ -f "${config_path}" ]] || { echo "Config not found: ${config_path}" >&2; exit 1; }

pipeline="${repo_root}/scripts/submit_pipeline.sh"
[[ -x "${pipeline}" || -f "${pipeline}" ]] || {
  echo "Pipeline launcher not found: ${pipeline}" >&2
  exit 1
}

run_variant() {
  local suffix="$1"
  shift
  local command=(
    bash "${pipeline}"
    --cluster "${cluster}"
    --config "${config_path}"
    --account "${account}"
  )
  local override
  if ((global_override_count)); then
    for override in "${global_overrides[@]}"; do
      command+=(--set "${override}")
    done
  fi
  for override in "$@"; do
    command+=(--set "${override}")
  done
  # Keep variant artifacts isolated even if a shared override happened to
  # include run_name.
  command+=(--set "run_name=${prefix}-${suffix}")
  if ((!submit)); then
    command+=(--dry-run)
  fi
  echo "### ${suffix}"
  "${command[@]}"
}

run_variant trained-mixed-p50 \
  stage1.input_mode=mixed \
  stage1.mixed_lambda=0.5 \
  stage1.probe_steps=50

run_variant trained-teacher-p50 \
  stage1.input_mode=teacher \
  stage1.probe_steps=50

run_variant trained-mixed-p300 \
  stage1.input_mode=mixed \
  stage1.mixed_lambda=0.5 \
  stage1.probe_steps=300

run_variant untrained-mixed-p0 \
  stage1.input_mode=mixed \
  stage1.mixed_lambda=0.5 \
  stage1.probe_steps=0

run_variant stage2-teacher \
  stage2.lambda_schedule=fixed \
  stage2.lambda_start=1.0 \
  stage2.lambda_end=1.0

run_variant stage2-fixed05 \
  stage2.lambda_schedule=fixed \
  stage2.lambda_start=0.5 \
  stage2.lambda_end=0.5
